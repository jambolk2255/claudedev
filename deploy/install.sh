#!/usr/bin/env bash
# One-time setup of StockFlow on an Ubuntu 22.04/24.04 server (arm64 or amd64), e.g. Oracle Cloud Always Free.
# Usage (from the repository root):  sudo bash deploy/install.sh
set -euo pipefail
# shellcheck source=deploy/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_root

# shellcheck disable=SC1091
. /etc/os-release
[[ "${ID:-}" == "ubuntu" ]] || die "Ubuntu 22.04 or 24.04 is required (found ${PRETTY_NAME:-unknown})."
ARCH="$(dpkg --print-architecture)"
export DEBIAN_FRONTEND=noninteractive

# ── 1. Swap for small machines (builds need memory) ─────────────────────────
MEM_KB="$(awk '/MemTotal/ {print $2}' /proc/meminfo)"
if ((MEM_KB < 4000000)) && ! swapon --show | grep -q .; then
  say "Adding 2 GB swap"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >>/etc/fstab
fi

# ── 2. Packages and Docker ──────────────────────────────────────────────────
say "Installing system packages"
apt-get update -y -qq
apt-get install -y -qq ca-certificates curl git openssl cron dnsutils >/dev/null

if ! command -v docker >/dev/null 2>&1; then
  say "Installing Docker"
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$ARCH signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $VERSION_CODENAME stable" >/etc/apt/sources.list.d/docker.list
  apt-get update -y -qq
  apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin >/dev/null
fi
systemctl enable --now docker >/dev/null
ok "Docker $(docker --version | awk '{print $3}' | tr -d ,)"

# ── 3. Settings (deploy/.env) ───────────────────────────────────────────────
# Docker Compose reads single-quoted values literally (no $ expansion) but can't escape a quote inside them.
squote() { printf "'%s'" "${1//\'/’}"; }
if [[ -f "$ENV_FILE" ]]; then
  ok "Using existing deploy/.env"
else
  say "A few questions"
  while true; do
    read -rp "Domain (e.g. mystock.duckdns.org): " DOMAIN
    DOMAIN="${DOMAIN#http*://}"
    DOMAIN="${DOMAIN%%/*}"
    [[ "$DOMAIN" =~ ^[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?(\.[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?)+$ ]] && break
    warn "That doesn't look like a domain name."
  done
  DUCKDNS_TOKEN=""
  if [[ "$DOMAIN" == *.duckdns.org ]]; then
    read -rsp "DuckDNS token (from duckdns.org, hidden): " DUCKDNS_TOKEN
    echo
  fi
  while true; do
    read -rp "Your email (platform admin login + certificate notices): " ADMIN_EMAIL
    [[ "$ADMIN_EMAIL" =~ ^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$ ]] && break
    warn "Enter a valid email address."
  done
  read -rp "Bank details shown to customers paying by transfer (optional, Enter to skip): " BANK

  umask 077
  {
    echo "# Generated by deploy/install.sh on $(date -u +%F). Keep private."
    echo "DOMAIN=$DOMAIN"
    echo "ACME_EMAIL=$ADMIN_EMAIL"
    echo "DUCKDNS_TOKEN=$DUCKDNS_TOKEN"
    echo "POSTGRES_PASSWORD=$(openssl rand -hex 24)"
    echo "JWT_ACCESS_SECRET=$(openssl rand -base64 48 | tr -d '\n')"
    echo "ENCRYPTION_KEY=$(openssl rand -base64 32)"
    echo "SAAS_MODE=true"
    echo "TRIAL_DAYS=14"
    echo "TRIAL_PLAN=business"
    echo "PLATFORM_ADMIN_EMAILS=$ADMIN_EMAIL"
    echo "BANK_TRANSFER_DETAILS=$(squote "$BANK")"
    echo "PAYHERE_MERCHANT_ID="
    echo "PAYHERE_MERCHANT_SECRET="
    echo "PAYHERE_SANDBOX=true"
    echo "NEXT_PUBLIC_GOOGLE_MAPS_API_KEY="
  } >"$ENV_FILE"
  chmod 600 "$ENV_FILE"
  umask 022
  ok "Saved deploy/.env (secrets generated)"
fi
DOMAIN="$(env_get DOMAIN)"
DUCKDNS_TOKEN="$(env_get DUCKDNS_TOKEN)"

# ── 4. DuckDNS: point the name at this server and keep it updated ──────────
if [[ "$DOMAIN" == *.duckdns.org && -n "$DUCKDNS_TOKEN" ]]; then
  SUB="${DOMAIN%.duckdns.org}"
  URL="https://www.duckdns.org/update?domains=${SUB##*.}&token=$DUCKDNS_TOKEN&ip="
  if [[ "$(curl -fsS --max-time 15 "$URL" || true)" == "OK" ]]; then ok "DuckDNS updated"; else warn "DuckDNS update failed — check the subdomain and token."; fi
  umask 077
  echo "*/5 * * * * root curl -fsS --max-time 15 '$URL' >/dev/null 2>&1" >/etc/cron.d/stockflow-duckdns
  umask 022
fi

# ── 5. Firewall: open HTTP/HTTPS (Oracle images reject them by default) ─────
say "Opening ports 80 and 443"
for rule in "-p tcp --dport 80" "-p tcp --dport 443" "-p udp --dport 443"; do
  # shellcheck disable=SC2086
  iptables -C INPUT $rule -j ACCEPT 2>/dev/null || iptables -I INPUT 1 $rule -j ACCEPT
done
# Persist only our rules: Oracle images restore /etc/iptables/rules.v4 at boot (it ends with a REJECT rule).
RULES=/etc/iptables/rules.v4
if [[ -f "$RULES" ]] && ! grep -q -- '--dport 443 -j ACCEPT' "$RULES"; then
  sed -i '0,/^-A INPUT .*-j REJECT/s//-A INPUT -p tcp -m tcp --dport 80 -j ACCEPT\n-A INPUT -p tcp -m tcp --dport 443 -j ACCEPT\n-A INPUT -p udp -m udp --dport 443 -j ACCEPT\n&/' "$RULES"
fi
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q "Status: active"; then ufw allow 80/tcp >/dev/null && ufw allow 443 >/dev/null; fi
ok "Firewall open (also add ingress rules for 80/443 in the Oracle VCN security list)"

# ── 6. DNS check ────────────────────────────────────────────────────────────
PUBLIC_IP="$(curl -fsS --max-time 10 https://api.ipify.org || true)"
DNS_IP="$(dig +short "$DOMAIN" A | tail -n 1 || true)"
if [[ -n "$PUBLIC_IP" && "$DNS_IP" != "$PUBLIC_IP" ]]; then
  warn "$DOMAIN points to '${DNS_IP:-nothing}', but this server is $PUBLIC_IP. HTTPS will work once DNS points here."
fi

# ── 7. Build and start ──────────────────────────────────────────────────────
say "Building and starting StockFlow (first build takes 5–15 minutes)"
cd "$REPO_DIR"
"${COMPOSE[@]}" up -d --build

# ── 8. Daily backups at 02:30 ───────────────────────────────────────────────
mkdir -p "$BACKUP_DIR" && chmod 700 "$BACKUP_DIR"
echo "30 2 * * * root bash $DEPLOY_DIR/backup.sh >>/var/log/stockflow-backup.log 2>&1" >/etc/cron.d/stockflow-backup
ok "Daily database backups go to $BACKUP_DIR (kept 14 days)"

wait_healthy || true
cat <<MSG

──────────────────────────────────────────────────────────────
  StockFlow:  https://$DOMAIN
  1. Open the link and choose "Start your free trial".
  2. Register with $(env_get PLATFORM_ADMIN_EMAILS) — that account can open https://$DOMAIN/admin
  3. Updates:  sudo bash deploy/update.sh      Backups:  sudo bash deploy/backup.sh
──────────────────────────────────────────────────────────────
MSG
